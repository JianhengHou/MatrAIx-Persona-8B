"""Job YAML shards that keep every persona paired with only its own decisions.

Harbor runs every agent entry against every task in a job, so each job must be
a block where all (persona, task) pairs are real decisions. A card only one
person saw becomes one job for that person with all of their tasks.

Only ``full`` shards are written by default. With ``--with-control`` the
``none`` shards are written too; they export ``MATRIX_PERSONA_MODE=none`` in the
header, which ``matraix run`` applies: the persona-free control on the same trials.
"""

from __future__ import annotations

import json
import os
import shutil
import subprocess
import sys
from collections import defaultdict
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path
from typing import Any

import yaml

from .paths import JOBS_ROOT, REPO_ROOT, rel
from .personas import load_persona_index
from .spec import DatasetAdapter
from .tasks import load_task_index

DEFAULT_MODEL = "anthropic/claude-sonnet-4-6"
AGENT_NAME = "persona-json-survey"
MODES = ("full", "none")
DEFAULT_MODES = ("full",)


def _environment_block() -> dict[str, Any]:
    from matraix.compute_family import resolve_compute_plan

    return resolve_compute_plan(
        execution_mode="auto", trial_profile="json_survey", compute_family="local"
    ).harbor_environment()


def plan_blocks(task_index: dict[str, Any], max_agents: int) -> list[tuple[list[str], list[str]]]:
    """Return (person_ids, task_paths) blocks covering every scored decision exactly once."""
    blocks: list[tuple[list[str], list[str]]] = []
    single: dict[str, list[str]] = defaultdict(list)
    for entry in task_index["tasks"].values():
        persons = list(dict.fromkeys(entry["persons"]))
        if len(persons) == 1:
            single[persons[0]].append(entry["path"])
            continue
        for start in range(0, len(persons), max_agents):
            blocks.append((persons[start : start + max_agents], [entry["path"]]))
    for person, paths in sorted(single.items()):
        blocks.append(([person], sorted(paths)))
    return blocks


def job_name(adapter: DatasetAdapter, mode: str, index: int, tag: str = "") -> str:
    prefix = "pf-{}-{}".format(adapter.slug, mode)
    if tag:
        prefix = "{}-{}".format(prefix, tag)
    return "{}-{:04d}".format(prefix, index)


def make_jobs(
    adapter: DatasetAdapter,
    *,
    modes: tuple[str, ...] = DEFAULT_MODES,
    model: str = DEFAULT_MODEL,
    max_agents: int = 100,
    n_concurrent: int = 4,
    clean: bool = True,
    tag: str = "",
) -> dict[str, list[str]]:
    task_index = load_task_index(adapter)
    personas = load_persona_index(adapter)
    blocks = plan_blocks(task_index, max_agents)
    environment = _environment_block()
    written: dict[str, list[str]] = {}
    for mode in modes:
        out = JOBS_ROOT / adapter.slug / mode
        if tag:
            out = out / tag
        if clean and out.exists():
            shutil.rmtree(out)
        out.mkdir(parents=True, exist_ok=True)
        paths: list[str] = []
        for i, (persons, tasks) in enumerate(blocks, start=1):
            name = job_name(adapter, mode, i, tag)
            config = {
                "job_name": name,
                "jobs_dir": "jobs",
                "n_attempts": 1,
                "timeout_multiplier": 1.0,
                "n_concurrent_trials": n_concurrent,
                "quiet": True,
                "environment": environment,
                "agents": [
                    {"name": AGENT_NAME, "model_name": model, "kwargs": {"persona_path": personas[p]}}
                    for p in persons
                ],
                "tasks": [{"path": t} for t in tasks],
            }
            header = [
                "# Generated by python -m persona.persona_fit (persona-fit)",
                "# Dataset: {} | mode: {} | shard {}/{} | {} persona(s) x {} task(s)".format(
                    adapter.slug, mode, i, len(blocks), len(persons), len(tasks)
                ),
                "#   export MATRIX_PERSONA_MODE={}".format(mode),
                "#",
                "#   uv run matraix run -c {}".format(rel(out / (name + ".yaml"))),
                "",
            ]
            path = out / (name + ".yaml")
            path.write_text("\n".join(header) + yaml.safe_dump(config, sort_keys=False), encoding="utf-8")
            paths.append(rel(path))
        written[mode] = paths
        (out / "index.json").write_text(json.dumps({"mode": mode, "jobs": paths}, indent=2) + "\n", encoding="utf-8")
    return written


def _read_env_local() -> dict[str, str]:
    """Provider keys from the gitignored repo-root ``.env.local`` (shell exports win)."""
    path = REPO_ROOT / ".env.local"
    values: dict[str, str] = {}
    if not path.is_file():
        return values
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.removeprefix("export ").split("=", 1)
        values[key.strip()] = value.strip().strip("'\"")
    return values


def job_dir(name: str) -> Path:
    return REPO_ROOT / "jobs" / name


def trial_needs_rerun(trial_dir: Path) -> bool:
    """A trial is reusable only when it finished without an exception.

    A wrong answer (reward 0, no exception) is a real decision and stays.
    Harbor treats an exception result as complete, so those directories have to
    be removed before resume or the failure is kept.
    """
    result_path = trial_dir / "result.json"
    if not result_path.is_file():
        return True
    try:
        result = json.loads(result_path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return True
    return bool(result.get("exception_info"))


def _trial_dirs(root: Path) -> list[Path]:
    if not root.is_dir():
        return []
    return sorted(
        path for path in root.iterdir()
        if path.is_dir() and not path.name.startswith("_")
    )


def _persona_path(agent: dict[str, Any]) -> str:
    kwargs = agent.get("kwargs") if isinstance(agent.get("kwargs"), dict) else {}
    return str(kwargs.get("persona_path") or "").strip()


def _finished_persona_paths(name: str) -> set[str]:
    done: set[str] = set()
    for trial in _trial_dirs(job_dir(name)):
        if trial_needs_rerun(trial):
            continue
        config_path = trial / "config.json"
        if not config_path.is_file():
            continue
        try:
            config = json.loads(config_path.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError):
            continue
        agent = config.get("agent") if isinstance(config.get("agent"), dict) else {}
        path = _persona_path(agent)
        if path:
            done.add(path)
    return done


def shard_needs_rerun(name: str) -> tuple[bool, str]:
    """Whether a shard should run, and why.

    A missing shard, or one without ``result.json``, has not finished. A
    finished shard reruns only when a trial failed, is incomplete, or is
    missing from the planned count. A clean shard is skipped.
    """
    root = job_dir(name)
    if not (root / "result.json").is_file():
        return True, "not finished"
    if not (root / "config.json").is_file():
        return True, "missing config"
    try:
        summary = json.loads((root / "result.json").read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return True, "unreadable result"
    trials = _trial_dirs(root)
    failed = [trial.name for trial in trials if trial_needs_rerun(trial)]
    n_total = summary.get("n_total_trials")
    missing = max(0, n_total - len(trials)) if isinstance(n_total, int) else 0
    if not failed and not missing:
        return False, "complete"
    parts = []
    if failed:
        shown = ", ".join(failed[:3])
        if len(failed) > 3:
            shown += ", +{}".format(len(failed) - 3)
        parts.append("{} failed trial(s): {}".format(len(failed), shown))
    if missing:
        parts.append("{} missing trial(s)".format(missing))
    return True, "; ".join(parts)


def prepare_shard(name: str) -> str:
    """Make a pending shard rerunnable in its original directory.

    Returns ``fresh`` when there is no Harbor config to resume, after deleting
    a partial directory. Returns ``resume`` after deleting only trials that
    recorded an exception; incomplete trials are left for Harbor to drop.
    Successful trials stay on disk and are not run again.
    """
    root = job_dir(name)
    if not (root / "config.json").is_file():
        if root.exists():
            shutil.rmtree(root)
        return "fresh"
    for trial in _trial_dirs(root):
        if trial_needs_rerun(trial) and (trial / "result.json").is_file():
            shutil.rmtree(trial)
    return "resume"


def _distributed_env(mode: str) -> dict[str, str]:
    env = dict(os.environ)
    for key, value in _read_env_local().items():
        env.setdefault(key, value)
    env.pop("MATRIX_SURVEY_TASK_PATH", None)
    env["MATRIX_PERSONA_MODE"] = mode
    from matraix.launch_env import build_launch_env

    return build_launch_env(REPO_ROOT, env)


def _run_distributed(config: str, mode: str) -> int:
    """Same host path as the first survey: one Harbor worker per trial.

    ``matraix run -c`` on these YAMLs is a single Harbor job. Playground's
    local-distributed coordinator is what fans a host survey out across workers.
    The YAML already names every persona and task, so it is used as-is.
    """
    from matraix.job_run import ensure_playground_imports, load_job_yaml

    ensure_playground_imports(REPO_ROOT)
    from backend.service.local_distributed_harbor import LocalDistributedHarborCoordinator

    name = Path(config).stem
    job = load_job_yaml(REPO_ROOT / config)
    if not job:
        raise FileNotFoundError(config)
    done = _finished_persona_paths(name)
    if done:
        agents = [
            agent for agent in (job.get("agents") or [])
            if _persona_path(agent) not in done
        ]
        if not agents:
            return 0
        job["agents"] = agents
        print(
            "[persona-fit] {} skip {} finished, run {}".format(name, len(done), len(agents)),
            flush=True,
        )
    env = _distributed_env(mode)

    def command_runner(command: list[str], *, cwd: Path, env: dict[str, str]) -> int:
        return subprocess.call(command, cwd=cwd, env=env)

    coordinator = LocalDistributedHarborCoordinator(
        repo_root=REPO_ROOT,
        job_name=name,
        job_config=job,
        launch_env=env,
        command_runner=command_runner,
        harbor_command=(sys.executable, "-m", "harbor.cli.main", "run"),
    )
    coordinator.run()
    return 0


def run_jobs(
    adapter: DatasetAdapter,
    mode: str,
    *,
    parallel: int = 1,
    limit: int | None = None,
    max_cost_usd: float | None = None,
    dry_run: bool = False,
    tag: str = "",
) -> list[tuple[str, int]]:
    """Run pending shards; clean shards are skipped, failed trials are replaced.

    A shard is pending when it has not finished, or when a finished shard still
    has a failed, incomplete, or missing trial. Those trials are deleted and
    Harbor resumes the same ``jobs/<shard>/``, so successful trials stay and
    the job ``result.json`` is overwritten with the replacement.
    """
    index_path = JOBS_ROOT / adapter.slug / mode
    if tag:
        index_path = index_path / tag
    index_path = index_path / "index.json"
    if not index_path.is_file():
        raise FileNotFoundError("{}: run `jobs --dataset {}` first".format(adapter.slug, adapter.slug))
    configs = json.loads(index_path.read_text(encoding="utf-8"))["jobs"]
    pending = []
    for config in configs:
        rerun, reason = shard_needs_rerun(Path(config).stem)
        if not rerun:
            continue
        pending.append(config)
        if reason != "not finished":
            print("[persona-fit] rerun {}: {}".format(Path(config).stem, reason), flush=True)
    if limit is not None:
        pending = pending[:limit]
    def run_one(config: str) -> tuple[str, int]:
        name = Path(config).stem
        if dry_run:
            print("[persona-fit] distributed {}".format(config))
            return config, 0
        print("[persona-fit] distributed {}".format(config), flush=True)
        try:
            return config, _run_distributed(config, mode)
        except Exception as exc:  # noqa: BLE001
            print("[persona-fit] distributed failed: {}".format(exc), file=sys.stderr, flush=True)
            return config, 1

    if parallel <= 1:
        return [run_one(c) for c in pending]
    with ThreadPoolExecutor(max_workers=parallel) as pool:
        return list(pool.map(run_one, pending))
